SELECT F.FILE_ID
     , F.NOTICE_ID
     , F.FILE_NAME
     , F.CONTENT_TYPE
     , F.FILE_SIZE
     , F.FILE_DATA
  FROM "INIT$_TB_NOTICE_FILE" F
  JOIN "INIT$_TB_NOTICE" N
    ON N.NOTICE_ID = F.NOTICE_ID
 WHERE F.FILE_ID = :fileId
   AND F.USE_YN = 'Y'
   AND N.USE_YN = 'Y'
   AND (N.POST_START_AT IS NULL OR N.POST_START_AT <= SYSTIMESTAMP)
   AND (N.POST_END_AT IS NULL OR N.POST_END_AT >= SYSTIMESTAMP)
;
