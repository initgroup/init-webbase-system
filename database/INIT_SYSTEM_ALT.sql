/*
 * INIT 시스템 DB 증분 반영 스크립트
 *
 * - 기존 테이블을 DROP하거나 데이터를 삭제하지 않습니다.
 * - 여러 번 실행해도 이미 존재하는 테이블, 컬럼, 제약조건은 건너뜁니다.
 * - 신규 컬럼은 INIT_SYSTEM_DDL.sql의 해당 테이블 맨 뒤에도 같은 순서로 추가합니다.
 * - Oracle은 기존 컬럼 사이에 새 컬럼을 물리적으로 삽입할 수 없으므로,
 *   DROP 없이 컬럼 순서를 유지하려면 신규 컬럼을 두 파일 모두 맨 뒤에 추가해야 합니다.
 */
SET SERVEROUTPUT ON

DECLARE
    FUNCTION OBJECT_EXISTS(
        P_OBJECT_NAME IN VARCHAR2
      , P_OBJECT_TYPE IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_OBJECTS
         WHERE OBJECT_NAME = UPPER(P_OBJECT_NAME)
           AND OBJECT_TYPE = UPPER(P_OBJECT_TYPE);
        RETURN V_COUNT > 0;
    END;

    FUNCTION COLUMN_EXISTS(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(P_TABLE_NAME)
           AND COLUMN_NAME = UPPER(P_COLUMN_NAME);
        RETURN V_COUNT > 0;
    END;

    FUNCTION CONSTRAINT_EXISTS(
        P_CONSTRAINT_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = UPPER(P_CONSTRAINT_NAME);
        RETURN V_COUNT > 0;
    END;

    PROCEDURE RUN_DDL(
        P_DDL IN CLOB
      , P_LABEL IN VARCHAR2
    ) IS
    BEGIN
        EXECUTE IMMEDIATE P_DDL;
        DBMS_OUTPUT.PUT_LINE('[OK] ' || P_LABEL);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('[ERROR] ' || P_LABEL || ' - ' || SQLERRM);
            RAISE;
    END;

    PROCEDURE CREATE_TABLE_IF_MISSING(
        P_TABLE_NAME IN VARCHAR2
      , P_DDL IN CLOB
    ) IS
    BEGIN
        IF OBJECT_EXISTS(P_TABLE_NAME, 'TABLE') THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] TABLE ' || P_TABLE_NAME || ' already exists');
        ELSE
            RUN_DDL(P_DDL, 'CREATE TABLE ' || P_TABLE_NAME);
        END IF;
    END;

    PROCEDURE ADD_COLUMN_IF_MISSING(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
      , P_COLUMN_DEFINITION IN VARCHAR2
    ) IS
    BEGIN
        IF COLUMN_EXISTS(P_TABLE_NAME, P_COLUMN_NAME) THEN
            DBMS_OUTPUT.PUT_LINE(
                '[SKIP] COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME || ' already exists'
            );
        ELSE
            RUN_DDL(
                'ALTER TABLE "' || UPPER(P_TABLE_NAME) || '" ADD ('
             || '"' || UPPER(P_COLUMN_NAME) || '" ' || P_COLUMN_DEFINITION || ')'
              , 'ADD COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME
            );
        END IF;
    END;

    PROCEDURE ADD_CONSTRAINT_IF_MISSING(
        P_CONSTRAINT_NAME IN VARCHAR2
      , P_DDL IN CLOB
    ) IS
    BEGIN
        IF CONSTRAINT_EXISTS(P_CONSTRAINT_NAME) THEN
            DBMS_OUTPUT.PUT_LINE(
                '[SKIP] CONSTRAINT ' || P_CONSTRAINT_NAME || ' already exists'
            );
        ELSE
            RUN_DDL(P_DDL, 'ADD CONSTRAINT ' || P_CONSTRAINT_NAME);
        END IF;
    END;

    PROCEDURE CREATE_INDEX_IF_MISSING(
        P_INDEX_NAME IN VARCHAR2
      , P_DDL IN CLOB
    ) IS
    BEGIN
        IF OBJECT_EXISTS(P_INDEX_NAME, 'INDEX') THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] INDEX ' || P_INDEX_NAME || ' already exists');
        ELSE
            RUN_DDL(P_DDL, 'CREATE INDEX ' || P_INDEX_NAME);
        END IF;
    END;
BEGIN
    /*
     * 2026-07 AI 학습 트렌드 대시보드
     *
     * 아래 컬럼 선언과 ADD 호출 순서는 INIT_SYSTEM_DDL.sql의
     * INIT$_TB_AI_TRAINING_RUN 컬럼 순서와 동일합니다.
     */
    CREATE_TABLE_IF_MISSING('INIT$_TB_AI_TRAINING_RUN', q'[
CREATE TABLE "INIT$_TB_AI_TRAINING_RUN" (
    "TRAINING_RUN_ID" NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL ENABLE
  , "MODEL_NAME" VARCHAR2(200 CHAR) NOT NULL ENABLE
  , "MODEL_VERSION" VARCHAR2(100 CHAR)
  , "STATUS_CODE" VARCHAR2(30 BYTE) DEFAULT 'PENDING' NOT NULL ENABLE
  , "DATASET_ROW_COUNT" NUMBER DEFAULT 0 NOT NULL ENABLE
  , "EPOCH_COUNT" NUMBER DEFAULT 0 NOT NULL ENABLE
  , "ACCURACY_SCORE" NUMBER(12, 8)
  , "LOSS_SCORE" NUMBER(12, 8)
  , "STARTED_AT" TIMESTAMP (6)
  , "COMPLETED_AT" TIMESTAMP (6)
  , "CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE
  , CONSTRAINT "INIT$_PK_AI_TRAINING_RUN" PRIMARY KEY ("TRAINING_RUN_ID")
  , CONSTRAINT "INIT$_CK_AI_TRAINING_STATUS"
        CHECK ("STATUS_CODE" IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED')) ENABLE
  , CONSTRAINT "INIT$_CK_AI_TRAINING_ACCURACY"
        CHECK ("ACCURACY_SCORE" IS NULL OR ("ACCURACY_SCORE" >= 0 AND "ACCURACY_SCORE" <= 1)) ENABLE
)
]');

    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'TRAINING_RUN_ID'
      , 'NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL ENABLE'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'MODEL_NAME'
      , 'VARCHAR2(200 CHAR) NOT NULL ENABLE'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'MODEL_VERSION'
      , 'VARCHAR2(100 CHAR)'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'STATUS_CODE'
      , 'VARCHAR2(30 BYTE) DEFAULT ''PENDING'' NOT NULL ENABLE'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'DATASET_ROW_COUNT'
      , 'NUMBER DEFAULT 0 NOT NULL ENABLE'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'EPOCH_COUNT'
      , 'NUMBER DEFAULT 0 NOT NULL ENABLE'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'ACCURACY_SCORE'
      , 'NUMBER(12, 8)'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'LOSS_SCORE'
      , 'NUMBER(12, 8)'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'STARTED_AT'
      , 'TIMESTAMP (6)'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'COMPLETED_AT'
      , 'TIMESTAMP (6)'
    );
    ADD_COLUMN_IF_MISSING(
        'INIT$_TB_AI_TRAINING_RUN'
      , 'CREATED_AT'
      , 'TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE'
    );

    ADD_CONSTRAINT_IF_MISSING(
        'INIT$_PK_AI_TRAINING_RUN'
      , 'ALTER TABLE "INIT$_TB_AI_TRAINING_RUN" '
     || 'ADD CONSTRAINT "INIT$_PK_AI_TRAINING_RUN" PRIMARY KEY ("TRAINING_RUN_ID")'
    );
    ADD_CONSTRAINT_IF_MISSING(
        'INIT$_CK_AI_TRAINING_STATUS'
      , 'ALTER TABLE "INIT$_TB_AI_TRAINING_RUN" '
     || 'ADD CONSTRAINT "INIT$_CK_AI_TRAINING_STATUS" '
     || 'CHECK ("STATUS_CODE" IN (''PENDING'', ''RUNNING'', ''COMPLETED'', ''FAILED'', ''CANCELLED'')) ENABLE'
    );
    ADD_CONSTRAINT_IF_MISSING(
        'INIT$_CK_AI_TRAINING_ACCURACY'
      , 'ALTER TABLE "INIT$_TB_AI_TRAINING_RUN" '
     || 'ADD CONSTRAINT "INIT$_CK_AI_TRAINING_ACCURACY" '
     || 'CHECK ("ACCURACY_SCORE" IS NULL '
     || 'OR ("ACCURACY_SCORE" >= 0 AND "ACCURACY_SCORE" <= 1)) ENABLE'
    );
    CREATE_INDEX_IF_MISSING(
        'INIT$_IX_AI_TRAINING_STATUS'
      , 'CREATE INDEX "INIT$_IX_AI_TRAINING_STATUS" '
     || 'ON "INIT$_TB_AI_TRAINING_RUN" ("STATUS_CODE", "COMPLETED_AT")'
    );
    RUN_DDL(
        q'[COMMENT ON TABLE "INIT$_TB_AI_TRAINING_RUN" IS 'AI model training run metrics']'
      , 'COMMENT INIT$_TB_AI_TRAINING_RUN'
    );
END;
