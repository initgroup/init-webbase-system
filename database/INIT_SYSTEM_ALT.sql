DECLARE
    FUNCTION OBJECT_EXISTS(
        P_OBJECT_NAME IN VARCHAR2
      , P_OBJECT_TYPE IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_OBJECTS
         WHERE OBJECT_NAME = UPPER(P_OBJECT_NAME)
           AND OBJECT_TYPE = UPPER(P_OBJECT_TYPE);
        RETURN V_COUNT > 0;
    END;

    FUNCTION COLUMN_EXISTS(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(P_TABLE_NAME)
           AND COLUMN_NAME = UPPER(P_COLUMN_NAME);
        RETURN V_COUNT > 0;
    END;

    FUNCTION CONSTRAINT_EXISTS(
        P_CONSTRAINT_NAME IN VARCHAR2
    ) RETURN BOOLEAN IS
        V_COUNT NUMBER;
    BEGIN
        SELECT COUNT(*)
          INTO V_COUNT
          FROM USER_CONSTRAINTS
         WHERE CONSTRAINT_NAME = UPPER(P_CONSTRAINT_NAME);
        RETURN V_COUNT > 0;
    END;

    PROCEDURE RUN_DDL(
        P_DDL IN CLOB
      , P_LABEL IN VARCHAR2
    ) IS
    BEGIN
        EXECUTE IMMEDIATE P_DDL;
        DBMS_OUTPUT.PUT_LINE('[OK] ' || P_LABEL);
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE('[ERROR] ' || P_LABEL || ' - ' || SQLERRM);
            RAISE;
    END;

    PROCEDURE CREATE_TABLE_IF_MISSING(
        P_TABLE_NAME IN VARCHAR2
      , P_DDL IN CLOB
    ) IS
    BEGIN
        IF OBJECT_EXISTS(P_TABLE_NAME, 'TABLE') THEN
            DBMS_OUTPUT.PUT_LINE('[SKIP] TABLE ' || P_TABLE_NAME || ' already exists');
        ELSE
            RUN_DDL(P_DDL, 'CREATE TABLE ' || P_TABLE_NAME);
        END IF;
    END;

    PROCEDURE ADD_COLUMN_IF_MISSING(
        P_TABLE_NAME IN VARCHAR2
      , P_COLUMN_NAME IN VARCHAR2
      , P_COLUMN_DEFINITION IN VARCHAR2
    ) IS
    BEGIN
        IF COLUMN_EXISTS(P_TABLE_NAME, P_COLUMN_NAME) THEN
            DBMS_OUTPUT.PUT_LINE(
                '[SKIP] COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME || ' already exists'
            );
        ELSE
            RUN_DDL(
                'ALTER TABLE "' || UPPER(P_TABLE_NAME) || '" ADD ('
             || '"' || UPPER(P_COLUMN_NAME) || '" ' || P_COLUMN_DEFINITION || ')'
              , 'ADD COLUMN ' || P_TABLE_NAME || '.' || P_COLUMN_NAME
            );
        END IF;
    END;

    PROCEDURE ADD_CONSTRAINT_IF_MISSING(
        P_CONSTRAINT_NAME IN VARCHAR2
      , P_DDL IN CLOB
    ) IS
    BEGIN
        IF CONSTRAINT_EXISTS(P_CONSTRAINT_NAME) THEN
            DBMS_OUTPUT.PUT_LINE(
                '[SKIP] CONSTRAINT ' || P_CONSTRAINT_NAME || ' already exists'
            );
        ELSE
            RUN_DDL(P_DDL, 'ADD CONSTRAINT ' || P_CONSTRAINT_NAME);
        END IF;
    END;

    PROCEDURE CREATE_INDEX_IF_MISSING(
