/*
 * INIT 시스템 DB 증분 반영 스크립트
 *
 * - 기존 테이블을 DROP하거나 데이터를 삭제하지 않습니다.
 * - 여러 번 실행해도 이미 존재하는 테이블, 컬럼, 제약조건은 건너뜁니다.
 * - 신규 컬럼은 INIT_SYSTEM_DDL.sql의 해당 테이블 맨 뒤에도 같은 순서로 추가합니다.
 * - Oracle은 기존 컬럼 사이에 새 컬럼을 물리적으로 삽입할 수 없으므로,
 *   DROP 없이 컬럼 순서를 유지하려면 신규 컬럼을 두 파일 모두 맨 뒤에 추가해야 합니다.
 */
