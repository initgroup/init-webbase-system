SELECT USER_ID
     , EMPLOYEE_NO
     , USER_NAME
     , DEPARTMENT_NAME
     , POSITION_NAME
     , JOB_TITLE
  FROM "INIT$_TB_USER"
 WHERE USE_YN = 'Y'
   AND EMPLOYMENT_STATUS_CODE IN ('ACTIVE', 'LEAVE')
 ORDER BY USER_NAME
        , USER_ID
;

-- [PROJECT_ASSIGNMENT_PROJECT]
