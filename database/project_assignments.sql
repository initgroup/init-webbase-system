     , PROJECT_NAME
     , PROJECT_START_DATE
     , PROJECT_END_DATE
     , CONTRACT_AMOUNT_VAT
     , PARTICIPATION_RATE
  FROM "INIT$_TB_PROJECT"
 WHERE PROJECT_ID = :projectId
;

-- [PROJECT_ASSIGNMENT_COMPANY_LIST]
SELECT C.PROJECT_COMPANY_ID
     , C.PROJECT_ID
     , C.COMPANY_NAME
     , C.PARTICIPATION_TYPE_CODE
     , C.SHARE_RATE
     , ROUND(P.CONTRACT_AMOUNT_VAT * C.SHARE_RATE / 100) AS ALLOCATED_SALES_AMOUNT
     , NVL(A.TOTAL_COST_AMOUNT, 0) AS TOTAL_COST_AMOUNT
     , NVL(A.TOTAL_SALES_AMOUNT, 0) AS TOTAL_SALES_AMOUNT
     , NVL(A.OPERATING_PROFIT, 0) AS OPERATING_PROFIT
     , C.NOTE
  FROM "INIT$_TB_PROJECT_COMPANY" C
  JOIN "INIT$_TB_PROJECT" P
    ON P.PROJECT_ID = C.PROJECT_ID
  LEFT JOIN (
        SELECT PROJECT_COMPANY_ID
             , SUM(TOTAL_COST_AMOUNT) AS TOTAL_COST_AMOUNT
             , SUM(TOTAL_SALES_AMOUNT) AS TOTAL_SALES_AMOUNT
             , SUM(OPERATING_PROFIT) AS OPERATING_PROFIT
          FROM "INIT$_TB_PROJECT_ASSIGNMENT"
         GROUP BY PROJECT_COMPANY_ID
       ) A
    ON A.PROJECT_COMPANY_ID = C.PROJECT_COMPANY_ID
 WHERE C.PROJECT_ID = :projectId
 ORDER BY C.PROJECT_COMPANY_ID
;

