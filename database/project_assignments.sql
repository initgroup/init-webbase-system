-- [PROJECT_ASSIGNMENT_REFERENCE_PROJECTS]
SELECT PROJECT_ID
     , PROJECT_YEAR
     , PROJECT_NAME
     , PROJECT_START_DATE
     , PROJECT_END_DATE
     , CONTRACT_AMOUNT_VAT
  FROM "INIT$_TB_PROJECT"
 WHERE STATUS_CODE <> 'CANCELLED'
 ORDER BY PROJECT_YEAR DESC
        , PROJECT_NAME
;

